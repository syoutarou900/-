def tr(lang, key, **params):
    table = STRINGS.get(lang, EN)
    text = table.get(key) or EN.get(key) or JA.get(key) or key
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError, ValueError):
            return text
    return text
