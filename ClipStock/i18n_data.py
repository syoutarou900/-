def t(lang, key, **kw):
    """Translate `key` for `lang`, falling back to Japanese, then the key."""
    d = TRANSLATIONS.get(lang) or TRANSLATIONS["ja"]
    s = d.get(key)
    if s is None:
        s = TRANSLATIONS["ja"].get(key, key)
    if kw:
        try:
            s = s.format(**kw)
        except Exception:
            pass
    return s


