DEEPL_TARGET = {
    "ja": "JA", "en": "EN-US", "es": "ES", "zh_CN": "ZH", "fr": "FR",
    "de": "DE", "pt": "PT-BR", "ru": "RU", "it": "IT", "tr": "TR",
    "id": "ID", "ko": "KO",
}
