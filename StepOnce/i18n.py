def tr(lang, key, **params):
    table = STRINGS.get(lang) or JA
    text = table.get(key)
    if text is None:
        text = JA.get(key, key)
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError):
            return text
    return text
